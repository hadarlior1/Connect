// Writes src/content/videos.ts: the step / module-intro videos that exist in public/avatar,
// and whether the English narration recordings are complete.
// The site only requests these, so a missing video never stalls playback (the host
// answers unknown paths with the SPA page, which some browsers never reject).
import { readdirSync, statSync, writeFileSync } from "node:fs";

// public/avatar may not exist at all (a voice-only training without avatar videos).
let files = [];
try {
  files = readdirSync(new URL("../public/avatar/", import.meta.url));
} catch {
  /* no avatar videos */
}
const has = (ext) => new Set(files.filter((f) => f.endsWith(ext)).map((f) => f.slice(0, -ext.length)));
const mp4 = has(".mp4");
const webm = has(".webm");
const steps = [...mp4].filter((id) => /^\d+\.\d+$/.test(id) && webm.has(id)).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
const intros = [...mp4].filter((id) => /^m\d+$/.test(id) && webm.has(id)).map((id) => id.slice(1)).sort();

// English narration is used only when every Hebrew narration has a non-empty English twin;
// until then the site speaks English with the browser's own voice.
const mp3s = (dir) => {
  try {
    return readdirSync(new URL(dir, import.meta.url)).filter((f) => f.endsWith(".mp3"));
  } catch {
    return [];
  }
};
const he = mp3s("../public/narration/");
const en = new Set(mp3s("../public/narration/en/").filter((f) => statSync(new URL(`../public/narration/en/${f}`, import.meta.url)).size > 0));
const enComplete = he.length > 0 && he.every((f) => en.has(f));

writeFileSync(
  new URL("../src/content/videos.ts", import.meta.url),
  `// Generated by scripts/list-videos.mjs (runs before dev/build). Do not edit.\n` +
    `export const STEP_VIDEOS: readonly string[] = ${JSON.stringify(steps)};\n` +
    `export const MODULE_INTROS: readonly string[] = ${JSON.stringify(intros)};\n` +
    `export const EN_NARRATION = ${enComplete};\n`,
);
console.log(`videos: ${steps.length} steps, ${intros.length} intros; English narration: ${enComplete ? "complete" : `${en.size}/${he.length}`}`);
